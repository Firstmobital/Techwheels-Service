CREATE OR REPLACE FUNCTION public.list_accounts_mechanical_cases()
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
SET row_security TO 'off'
AS $$
DECLARE
  v_rows jsonb;
BEGIN
  IF NOT public.accounts_can_access() THEN
    RAISE EXCEPTION 'permission denied: requires accounts view'
      USING ERRCODE = '42501';
  END IF;

  SELECT COALESCE(
    jsonb_agg(to_jsonb(x) ORDER BY x.invoice_done_at DESC NULLS LAST, x.reception_entry_id DESC),
    '[]'::jsonb
  )
    INTO v_rows
    FROM (
      SELECT
        e.id AS reception_entry_id,
        e.jc_number,
        e.reg_number,
        e.model,
        e.service_type,
        e.sa_name,
        e.sa_display_name,
        e.sa_employee_code,
        e.branch,
        e.owner_name,
        e.owner_phone,
        e.invoice_done_at,
        e.invoice_done_by,
        e.created_at,
        inv.invoice_number,
        inv.invoice_date,
        inv.billed_amount,
        inv.payment_status,
        inv.amount_received,
        inv.payment_notes,
        inv.captured_by,
        inv.captured_at,
        inv.updated_at AS invoice_updated_at
      FROM public.service_reception_entries e
      LEFT JOIN public.accounts_mechanical_invoices inv
        ON inv.reception_entry_id = e.id
      WHERE e.invoice_done_at IS NOT NULL
        AND NULLIF(btrim(e.jc_number), '') IS NOT NULL
        AND public.is_floor_incharge_service_type(e.service_type)
    ) x;

  RETURN v_rows;
END;
$$;

CREATE OR REPLACE FUNCTION public.upsert_accounts_mechanical_invoice(
  p_reception_entry_id bigint,
  p_invoice_number text DEFAULT NULL,
  p_invoice_date date DEFAULT NULL,
  p_billed_amount numeric DEFAULT NULL,
  p_payment_status text DEFAULT NULL,
  p_amount_received numeric DEFAULT NULL,
  p_payment_notes text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
SET row_security TO 'off'
AS $$
DECLARE
  v_entry public.service_reception_entries%ROWTYPE;
  v_actor text;
  v_status text;
  v_row public.accounts_mechanical_invoices%ROWTYPE;
BEGIN
  IF NOT public.accounts_can_access() THEN
    RAISE EXCEPTION 'permission denied: requires accounts view'
      USING ERRCODE = '42501';
  END IF;

  SELECT * INTO v_entry
    FROM public.service_reception_entries
   WHERE id = p_reception_entry_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'reception entry % not found', p_reception_entry_id
      USING ERRCODE = 'P0002';
  END IF;
  IF v_entry.invoice_done_at IS NULL THEN
    RAISE EXCEPTION 'case is not Mark Done on Service Advisor'
      USING ERRCODE = '23514';
  END IF;
  IF NOT public.is_floor_incharge_service_type(v_entry.service_type) THEN
    RAISE EXCEPTION 'not a mechanical Floor Incharge service type'
      USING ERRCODE = '23514';
  END IF;
  IF NULLIF(btrim(v_entry.jc_number), '') IS NULL THEN
    RAISE EXCEPTION 'jc_number is required'
      USING ERRCODE = '23514';
  END IF;

  v_status := lower(btrim(COALESCE(p_payment_status, 'pending')));
  IF v_status NOT IN ('pending', 'partial', 'received', 'not_received') THEN
    RAISE EXCEPTION 'invalid payment_status'
      USING ERRCODE = '23514';
  END IF;
  IF p_billed_amount IS NOT NULL AND p_billed_amount < 0 THEN
    RAISE EXCEPTION 'billed_amount cannot be negative'
      USING ERRCODE = '23514';
  END IF;
  IF p_amount_received IS NOT NULL AND p_amount_received < 0 THEN
    RAISE EXCEPTION 'amount_received cannot be negative'
      USING ERRCODE = '23514';
  END IF;

  v_actor := COALESCE(
    NULLIF(auth.jwt() ->> 'email', ''),
    NULLIF(auth.uid()::text, ''),
    'system'
  );

  INSERT INTO public.accounts_mechanical_invoices (
    reception_entry_id, jc_number, invoice_number, invoice_date, billed_amount,
    payment_status, amount_received, payment_notes, captured_by, captured_at, updated_at
  ) VALUES (
    p_reception_entry_id,
    btrim(v_entry.jc_number),
    NULLIF(btrim(p_invoice_number), ''),
    p_invoice_date,
    CASE WHEN p_billed_amount IS NULL THEN NULL ELSE round(p_billed_amount, 2) END,
    v_status,
    CASE WHEN p_amount_received IS NULL THEN NULL ELSE round(p_amount_received, 2) END,
    NULLIF(btrim(p_payment_notes), ''),
    v_actor,
    now(),
    now()
  )
  ON CONFLICT (reception_entry_id) DO UPDATE SET
    jc_number = EXCLUDED.jc_number,
    invoice_number = EXCLUDED.invoice_number,
    invoice_date = EXCLUDED.invoice_date,
    billed_amount = EXCLUDED.billed_amount,
    payment_status = EXCLUDED.payment_status,
    amount_received = EXCLUDED.amount_received,
    payment_notes = EXCLUDED.payment_notes,
    updated_at = now();

  SELECT * INTO v_row
    FROM public.accounts_mechanical_invoices
   WHERE reception_entry_id = p_reception_entry_id;

  RETURN to_jsonb(v_row);
END;
$$;

