CREATE TABLE IF NOT EXISTS public.accounts_mechanical_invoices (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reception_entry_id bigint NOT NULL REFERENCES public.service_reception_entries(id) ON DELETE CASCADE,
  jc_number text NOT NULL,
  invoice_number text,
  invoice_date date,
  billed_amount numeric(14,2),
  payment_status text NOT NULL DEFAULT 'pending',
  amount_received numeric(14,2),
  payment_notes text,
  captured_by text,
  captured_at timestamptz DEFAULT now() NOT NULL,
  updated_at timestamptz DEFAULT now() NOT NULL,
  CONSTRAINT accounts_mechanical_invoices_reception_uid UNIQUE (reception_entry_id),
  CONSTRAINT accounts_mechanical_invoices_jc_not_blank CHECK (length(btrim(jc_number)) > 0),
  CONSTRAINT accounts_mechanical_invoices_pay_check CHECK (
    payment_status = ANY (ARRAY['pending'::text, 'partial'::text, 'received'::text, 'not_received'::text])
  ),
  CONSTRAINT accounts_mechanical_invoices_billed_check CHECK (
    billed_amount IS NULL OR billed_amount >= 0
  ),
  CONSTRAINT accounts_mechanical_invoices_received_check CHECK (
    amount_received IS NULL OR amount_received >= 0
  )
);

CREATE INDEX IF NOT EXISTS idx_accounts_mech_inv_jc
  ON public.accounts_mechanical_invoices (jc_number);
