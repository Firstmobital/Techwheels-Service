-- Salary totals per month and branch only: P&L users never receive individual salaries or need Payroll access.
CREATE FUNCTION public.pnl_payroll_cost(p_from date, p_to date)
RETURNS TABLE (payroll_month date, branch text, gross numeric, month_status text)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path TO 'public' AS $$
BEGIN
  IF NOT COALESCE(public.has_module_view('pnl_report'), false) THEN
    RAISE EXCEPTION 'Not allowed to view Profit & Loss data' USING ERRCODE = '42501';
  END IF;
  RETURN QUERY
    SELECT e.payroll_month, e.branch_snapshot, sum(e.gross_payout), COALESCE(m.status, 'draft')
      FROM public.payroll_entries e
      LEFT JOIN public.payroll_months m ON m.payroll_month = e.payroll_month
     WHERE e.payroll_month BETWEEN date_trunc('month', p_from)::date AND p_to
     GROUP BY e.payroll_month, e.branch_snapshot, m.status;
END;
$$;
REVOKE ALL ON FUNCTION public.pnl_payroll_cost(date, date) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.pnl_payroll_cost(date, date) TO authenticated, service_role;
