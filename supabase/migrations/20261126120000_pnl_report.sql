CREATE TABLE public.pnl_settings (
  id smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  labour_margin_pct numeric(5,2) NOT NULL DEFAULT 100 CHECK (labour_margin_pct BETWEEN 0 AND 100),
  parts_margin_pct numeric(5,2) NOT NULL DEFAULT 9 CHECK (parts_margin_pct BETWEEN 0 AND 100),
  revenue_basis text NOT NULL DEFAULT 'ex_gst' CHECK (revenue_basis IN ('ex_gst', 'incl_gst')),
  updated_by uuid DEFAULT auth.uid(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
