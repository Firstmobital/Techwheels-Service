CREATE TABLE public.pnl_expenses (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  expense_month date NOT NULL CHECK (EXTRACT(day FROM expense_month) = 1),
  branch text NOT NULL CHECK (branch IN ('Common', 'Ajmer Road', 'Sitapura', 'Tonk', 'Shahpura')),
  head_id bigint NOT NULL REFERENCES public.pnl_expense_heads(id) ON DELETE RESTRICT,
  amount numeric(14,2) NOT NULL CHECK (amount >= 0),
  updated_by uuid DEFAULT auth.uid(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT pnl_expenses_month_branch_head_key UNIQUE (expense_month, branch, head_id)
);

CREATE FUNCTION public.pnl_stamp_row() RETURNS trigger LANGUAGE plpgsql SET search_path TO 'public' AS $$
BEGIN
  NEW.updated_by := auth.uid();
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;
CREATE TRIGGER pnl_settings_stamp BEFORE UPDATE ON public.pnl_settings FOR EACH ROW EXECUTE FUNCTION public.pnl_stamp_row();
CREATE TRIGGER pnl_expenses_stamp BEFORE INSERT OR UPDATE ON public.pnl_expenses FOR EACH ROW EXECUTE FUNCTION public.pnl_stamp_row();

