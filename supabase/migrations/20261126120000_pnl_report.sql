CREATE TABLE public.pnl_expense_heads (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text UNIQUE,                       -- only 'salary' has special behaviour (Payroll fallback)
  name text NOT NULL CHECK (length(btrim(name)) > 0),
  category text NOT NULL CHECK (category IN ('People', 'Premises', 'Operations', 'Admin', 'Finance')),
