  sort_order integer NOT NULL DEFAULT 1000,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX pnl_expense_heads_name_key ON public.pnl_expense_heads (lower(btrim(name)));

