CREATE OR REPLACE FUNCTION public.customer_list_helpdesk_contacts(p_session_token text)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO public, extensions
AS $$
BEGIN
  PERFORM public.customer_require_session(p_session_token);

  RETURN COALESCE(
    (
      SELECT jsonb_agg(
        jsonb_build_object(
          'id', c.id,
          'group_key', c.group_key,
          'sort_order', c.sort_order,
          'level_label', c.level_label,
          'contact_name', c.contact_name,
          'role_title', c.role_title,
          'description', c.description,
          'phone', c.phone,
          'email', c.email,
          'icon_emoji', c.icon_emoji,
          'badge_variant', c.badge_variant,
          'chat_contact_key', c.chat_contact_key
        )
        ORDER BY c.group_key, c.sort_order, c.id
      )
      FROM public.settings_customer_helpdesk_contacts c
      WHERE c.is_active = true
    ),
    '[]'::jsonb
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.customer_helpdesk_peer_name(p_contact_key text, p_default_sa text)
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT COALESCE(
    (
      SELECT c.contact_name
      FROM public.settings_customer_helpdesk_contacts c
      WHERE c.is_active = true
        AND c.chat_contact_key = btrim(COALESCE(p_contact_key, ''))
      LIMIT 1
    ),
    CASE btrim(COALESCE(p_contact_key, 'advisor'))
      WHEN 'payal' THEN 'Payal Makhija'
      WHEN 'govind' THEN 'Govind Singh'
      WHEN 'rajesh' THEN 'Mr Rajesh Panday'
      WHEN 'tata_akshay' THEN 'Mr Akshay Jethalia'
      WHEN 'tata_gurmeet' THEN 'Mr Gurmeet Singh'
      ELSE COALESCE(NULLIF(btrim(p_default_sa), ''), 'Service advisor')
    END
  );
$$;

