-- Admin-managed customer helpdesk / escalation contacts (mobile + web portal).
-- Customer reads: customer_list_helpdesk_contacts(session) only (anon has no table grant).
-- Staff CRUD: authenticated + settings module (or admin) via Settings UI.
-- Rollback:
--   DROP FUNCTION IF EXISTS public.customer_list_helpdesk_contacts(text);
--   DROP TABLE IF EXISTS public.settings_customer_helpdesk_contacts CASCADE;

CREATE TABLE IF NOT EXISTS public.settings_customer_helpdesk_contacts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_key text NOT NULL CHECK (group_key = ANY (ARRAY['dealership'::text, 'tata_motors'::text])),
  sort_order integer NOT NULL DEFAULT 0,
  level_label text NOT NULL,
  contact_name text NOT NULL,
  role_title text NOT NULL,
  description text,
  phone text NOT NULL,
  email text,
  icon_emoji text DEFAULT '👤'::text,
  badge_variant text NOT NULL DEFAULT 'blue'::text CHECK (
    badge_variant = ANY (ARRAY['blue'::text, 'amber'::text, 'rose'::text, 'indigo'::text, 'emerald'::text])
  ),
  chat_contact_key text,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT settings_customer_helpdesk_contacts_chat_key_unique UNIQUE (chat_contact_key)
);

COMMENT ON TABLE public.settings_customer_helpdesk_contacts IS
  'Customer helpdesk / escalation matrix. Edited in Settings; mobile loads active rows via customer_list_helpdesk_contacts.';

CREATE INDEX IF NOT EXISTS idx_settings_customer_helpdesk_contacts_group_sort
  ON public.settings_customer_helpdesk_contacts (group_key, sort_order, id);

CREATE OR REPLACE FUNCTION public.settings_customer_helpdesk_contacts_touch_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_settings_customer_helpdesk_contacts_updated_at ON public.settings_customer_helpdesk_contacts;
CREATE TRIGGER trg_settings_customer_helpdesk_contacts_updated_at
  BEFORE UPDATE ON public.settings_customer_helpdesk_contacts
  FOR EACH ROW
  EXECUTE FUNCTION public.settings_customer_helpdesk_contacts_touch_updated_at();

